/*
  bahtText.test.js — ทดสอบการแปลงจำนวนเงินเป็นตัวอักษรไทย
  ครอบคลุมทุกตัวอย่างในตาราง Spec.md ข้อ 3.3 และกฎย่อยทั้งหมด
*/

import { describe, it, expect } from "vitest";
import { bahtText } from "./bahtText.js";

describe("ตัวอย่างทุกเคสในตาราง Spec ข้อ 3.3", () => {
  it("1000 = หนึ่งพันบาทถ้วน", () => {
    expect(bahtText(1000)).toBe("หนึ่งพันบาทถ้วน");
  });

  it("21 = ยี่สิบเอ็ดบาทถ้วน", () => {
    expect(bahtText(21)).toBe("ยี่สิบเอ็ดบาทถ้วน");
  });

  it("11 = สิบเอ็ดบาทถ้วน", () => {
    expect(bahtText(11)).toBe("สิบเอ็ดบาทถ้วน");
  });

  it("101 = หนึ่งร้อยเอ็ดบาทถ้วน", () => {
    expect(bahtText(101)).toBe("หนึ่งร้อยเอ็ดบาทถ้วน");
  });

  it("1000000 = หนึ่งล้านบาทถ้วน", () => {
    expect(bahtText(1000000)).toBe("หนึ่งล้านบาทถ้วน");
  });

  it("1234567.89 = หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์", () => {
    expect(bahtText(1234567.89)).toBe(
      "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์"
    );
  });

  it("0.5 = ห้าสิบสตางค์ (ไม่มีคำว่า ศูนย์บาท นำหน้า)", () => {
    expect(bahtText(0.5)).toBe("ห้าสิบสตางค์");
  });

  it("0 = ศูนย์บาทถ้วน", () => {
    expect(bahtText(0)).toBe("ศูนย์บาทถ้วน");
  });

  it("1000000000000 = หนึ่งล้านล้านบาทถ้วน (หลักล้านซ้อน)", () => {
    expect(bahtText(1000000000000)).toBe("หนึ่งล้านล้านบาทถ้วน");
  });
});

describe("กฎย่อยของหลักสิบและหลักหน่วย", () => {
  it("หลักสิบเป็น 1 อ่านว่า สิบ ไม่ใช่ หนึ่งสิบ", () => {
    expect(bahtText(10)).toBe("สิบบาทถ้วน");
    expect(bahtText(15)).toBe("สิบห้าบาทถ้วน");
  });

  it("หลักสิบเป็น 2 อ่านว่า ยี่สิบ", () => {
    expect(bahtText(20)).toBe("ยี่สิบบาทถ้วน");
    expect(bahtText(25)).toBe("ยี่สิบห้าบาทถ้วน");
  });

  it("หลักสิบตั้งแต่ 3 ขึ้นไป อ่านตามปกติ", () => {
    expect(bahtText(30)).toBe("สามสิบบาทถ้วน");
    expect(bahtText(90)).toBe("เก้าสิบบาทถ้วน");
  });

  it("หลักหน่วยเป็น 1 อ่านว่า เอ็ด เมื่อมีหลักสิบนำหน้า", () => {
    expect(bahtText(31)).toBe("สามสิบเอ็ดบาทถ้วน");
    expect(bahtText(91)).toBe("เก้าสิบเอ็ดบาทถ้วน");
    expect(bahtText(111)).toBe("หนึ่งร้อยสิบเอ็ดบาทถ้วน");
  });

  /*
    กฎ เอ็ด ต้องทำงานทุกหลัก ไม่ใช่เฉพาะตอนหลักสิบไม่เป็นศูนย์
    ชุดนี้ตรวจว่าหลักที่นำหน้าเป็นร้อย พัน หมื่น แสน หรือล้าน ก็ต้องอ่านว่า เอ็ด เหมือนกัน
  */
  it("หลักหน่วยเป็น 1 อ่านว่า เอ็ด แม้หลักสิบเป็นศูนย์", () => {
    expect(bahtText(101)).toBe("หนึ่งร้อยเอ็ดบาทถ้วน");
    expect(bahtText(201)).toBe("สองร้อยเอ็ดบาทถ้วน");
    expect(bahtText(1001)).toBe("หนึ่งพันเอ็ดบาทถ้วน");
    expect(bahtText(10001)).toBe("หนึ่งหมื่นเอ็ดบาทถ้วน");
    expect(bahtText(100001)).toBe("หนึ่งแสนเอ็ดบาทถ้วน");
    expect(bahtText(1000101)).toBe("หนึ่งล้านหนึ่งร้อยเอ็ดบาทถ้วน");
  });

  it("เลข 1 ที่อยู่โดด ๆ ยังอ่านว่า หนึ่ง", () => {
    expect(bahtText(1)).toBe("หนึ่งบาทถ้วน");
  });
});

describe("หลักล้านและหลักล้านซ้อน", () => {
  it("อ่านเลขหลักล้านที่มีเศษต่อท้ายได้ถูกต้อง", () => {
    expect(bahtText(1000001)).toBe("หนึ่งล้านเอ็ดบาทถ้วน");
    expect(bahtText(1000011)).toBe("หนึ่งล้านสิบเอ็ดบาทถ้วน");
    expect(bahtText(2000000)).toBe("สองล้านบาทถ้วน");
  });

  it("อ่านเลขหลักสิบล้านและร้อยล้านได้", () => {
    expect(bahtText(12000000)).toBe("สิบสองล้านบาทถ้วน");
    expect(bahtText(999999999)).toBe(
      "เก้าร้อยเก้าสิบเก้าล้านเก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทถ้วน"
    );
  });

  it("อ่านหลักล้านซ้อนที่มีเศษต่อท้ายได้", () => {
    expect(bahtText(1000000000001)).toBe("หนึ่งล้านล้านเอ็ดบาทถ้วน");
    expect(bahtText(2000000000000)).toBe("สองล้านล้านบาทถ้วน");
  });
});

describe("การอ่านสตางค์", () => {
  it("สตางค์หลักเดียว อ่านว่า หนึ่ง ไม่ใช่ เอ็ด (เพราะเป็นเลขหลักเดียวโดด ๆ)", () => {
    expect(bahtText(0.01)).toBe("หนึ่งสตางค์");
    expect(bahtText(5.09)).toBe("ห้าบาทเก้าสตางค์");
  });

  it("สตางค์ที่มีหลักสิบนำหน้า ใช้กฎ เอ็ด ตามปกติ", () => {
    expect(bahtText(1.11)).toBe("หนึ่งบาทสิบเอ็ดสตางค์");
    expect(bahtText(1.21)).toBe("หนึ่งบาทยี่สิบเอ็ดสตางค์");
  });

  it("ไม่มีเศษสตางค์ ต้องลงท้ายด้วย บาทถ้วน", () => {
    expect(bahtText(500)).toBe("ห้าร้อยบาทถ้วน");
    expect(bahtText(500.0)).toBe("ห้าร้อยบาทถ้วน");
  });

  it("ปัดเศษทศนิยมเกิน 2 ตำแหน่งแบบ half-up ก่อนอ่าน", () => {
    expect(bahtText(1.005)).toBe("หนึ่งบาทหนึ่งสตางค์");
    expect(bahtText(0.994)).toBe("เก้าสิบเก้าสตางค์");
    expect(bahtText(0.999)).toBe("หนึ่งบาทถ้วน");
  });
});

describe("กรณีข้อมูลผิดปกติ", () => {
  it("ค่าที่ไม่ใช่ตัวเลข คืนข้อความว่าง ไม่คืน ศูนย์บาทถ้วน", () => {
    expect(bahtText(null)).toBe("");
    expect(bahtText(undefined)).toBe("");
    expect(bahtText("")).toBe("");
    expect(bahtText("ห้าสิบ")).toBe("");
    expect(bahtText(NaN)).toBe("");
    expect(bahtText(Infinity)).toBe("");
  });

  it("รับข้อความตัวเลขที่มีจุลภาคคั่นหลักพันได้", () => {
    expect(bahtText("1,000")).toBe("หนึ่งพันบาทถ้วน");
    expect(bahtText("1234567.89")).toBe(
      "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์"
    );
  });

  it("จำนวนติดลบ นำหน้าด้วยคำว่า ลบ", () => {
    expect(bahtText(-50)).toBe("ลบห้าสิบบาทถ้วน");
  });
});
