-- =====================================================================
-- 008_payee_usage_stats.sql
-- มุมมองสรุปการใช้งานของผู้ถูกหักภาษีแต่ละราย
-- ต้องรันหลัง 007
--
-- -------------------------------------------------------------------
-- ทำไมต้องมีไฟล์นี้
-- -------------------------------------------------------------------
-- หน้าทะเบียนผู้ถูกหักภาษีต้องแสดง 2 คอลัมน์ที่ไม่ได้เก็บไว้ในตาราง payees
-- คือ "จำนวนเอกสารที่เคยออก" และ "ใช้ล่าสุดเมื่อ"
-- ทั้งสองค่านี้ต้องนับจากตาราง wht_certificates จริง ๆ
--
-- ถ้าให้หน้าเว็บดึงเอกสารทั้งหมดมานับเอง จะช้ามากเมื่อข้อมูลเยอะขึ้น
-- (เช่น ผู้ถูกหัก 20 รายที่มีเอกสารรายละ 100 ใบ ต้องโหลด 2,000 แถวมานับ)
-- จึงให้ฐานข้อมูลนับมาให้เสร็จแล้วส่งเฉพาะผลสรุปกลับมา
--
-- -------------------------------------------------------------------
-- นับเฉพาะเอกสารที่ "ออกไปแล้วจริง"
-- -------------------------------------------------------------------
-- ใบร่าง (draft) ไม่นับ เพราะยังไม่ได้ออกให้ใคร อาจถูกลบทิ้งได้
-- ส่วนเอกสารที่ยกเลิก (void) ยังนับอยู่ เพราะเคยออกไปจริงแล้ว
-- เพียงแต่ถูกยกเลิกภายหลัง ซึ่งยังถือเป็นประวัติการใช้งานของรายนั้น
-- =====================================================================

create or replace view public.payee_usage_stats
with (security_invoker = true) as
select
  c.payee_id                        as payee_id,
  count(*)::int                     as certificate_count,   -- จำนวนเอกสารที่เคยออก
  max(c.issue_date)                 as last_used_date       -- วันที่ใช้ล่าสุด
from public.wht_certificates c
where c.payee_id is not null
  and c.status <> 'draft'
group by c.payee_id;

comment on view public.payee_usage_stats is
  'สรุปจำนวนเอกสารที่เคยออกและวันที่ใช้ล่าสุดของผู้ถูกหักภาษีแต่ละราย';

-- =====================================================================
-- security_invoker = true คือหัวใจความปลอดภัยของไฟล์นี้
--
-- ปกติมุมมอง (view) จะทำงานด้วยสิทธิ์ของ "เจ้าของมุมมอง" ซึ่งมองเห็นข้อมูลทุกองค์กร
-- ถ้าปล่อยแบบนั้น ผู้ใช้จะเห็นสถิติของบริษัทอื่นได้ ซึ่งผิดหลักการของระบบนี้
--
-- การตั้ง security_invoker = true บังคับให้มุมมองทำงานด้วยสิทธิ์ของ "คนที่เรียกดู"
-- กฎ RLS ของตาราง wht_certificates ในไฟล์ 004 จึงถูกนำมาใช้ตามปกติ
-- ผู้ใช้แต่ละคนจะเห็นสถิติเฉพาะเอกสารขององค์กรตัวเองเท่านั้น
-- =====================================================================

-- ให้สิทธิ์เฉพาะผู้ที่ล็อกอินแล้ว และปิดไม่ให้ผู้ที่ยังไม่ล็อกอินแตะ
-- (สอดคล้องกับหลักการเดียวกับไฟล์ 005)
revoke all on public.payee_usage_stats from anon;
grant select on public.payee_usage_stats to authenticated;


-- =====================================================================
-- คำสั่งตรวจสอบ (รันแล้วดูผลได้เลย ไม่ได้แก้อะไร)
-- =====================================================================

-- ตรวจข้อ 1: มุมมองถูกสร้างแล้วและตั้ง security_invoker ไว้จริงหรือไม่
-- ผลที่ถูกต้อง: ได้ 1 แถว และช่อง "ผลตรวจ" ขึ้น OK
select
  c.relname                                                  as "ชื่อมุมมอง",
  coalesce(
    (select option_value
     from pg_options_to_table(c.reloptions)
     where option_name = 'security_invoker'),
    'ไม่ได้ตั้ง'
  )                                                          as "ค่า security_invoker",
  case
    when (select option_value
          from pg_options_to_table(c.reloptions)
          where option_name = 'security_invoker') in ('true', 'on')
    then 'OK'
    else 'ผิด — ผู้ใช้อาจเห็นข้อมูลข้ามองค์กรได้'
  end                                                        as "ผลตรวจ"
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relname = 'payee_usage_stats';

-- ตรวจข้อ 2: ผู้ที่ยังไม่ล็อกอิน (anon) ต้องไม่มีสิทธิ์แตะมุมมองนี้
-- ผลที่ถูกต้อง: ต้องไม่มีแถวใดถูกส่งกลับมา (0 rows)
select
  grantee        as "บทบาท",
  privilege_type as "สิทธิ์ที่หลุดให้ anon"
from information_schema.role_table_grants
where table_schema = 'public'
  and table_name = 'payee_usage_stats'
  and grantee = 'anon';

-- ตรวจข้อ 3: ลองเรียกดูผลจริง
-- ผลที่ถูกต้อง: ตอนนี้ยังไม่มีเอกสารในระบบ (ยังไม่ถึง Phase 6) จึงควรได้ 0 แถว
-- ซึ่งถือว่าถูกต้อง ไม่ใช่ข้อผิดพลาด
select * from public.payee_usage_stats;
