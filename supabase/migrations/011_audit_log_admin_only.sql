-- จำกัดการอ่านประวัติการใช้งานไว้เฉพาะผู้ดูแลระบบ
-- ต้องรันหลัง 010
--
-- -------------------------------------------------------------------
-- ทำไมต้องแก้
-- -------------------------------------------------------------------
-- กฎเดิมในไฟล์ 004 เขียนไว้ว่าใครก็ได้ในองค์กรอ่านตาราง audit_logs ได้
--     using (org_id = get_my_org_id())
--
-- แต่ Phase 9 กำหนดให้หน้าดูประวัติการใช้งานเป็นของผู้ดูแลระบบเท่านั้น
-- ถ้าซ่อนแค่เมนูบนหน้าจอ แต่กฎในฐานข้อมูลยังเปิดให้ทุกคนอ่านได้
-- ผู้ใช้ทั่วไปที่รู้วิธีเรียกข้อมูลตรง ๆ ก็ยังดูได้อยู่ดี ซึ่งไม่ถือว่ากันสิทธิ์จริง
--
-- ประวัติการใช้งานเป็นข้อมูลอ่อนไหว เพราะบอกได้ว่าใครทำอะไรเมื่อไหร่
-- จึงควรจำกัดให้เฉพาะผู้ดูแลระบบเหมือนหน้าจัดการผู้ใช้
--
-- -------------------------------------------------------------------
-- สิ่งที่ไม่เปลี่ยน
-- -------------------------------------------------------------------
-- สิทธิ์ "เขียนเพิ่ม" ยังเป็นของทุกคนในองค์กรเหมือนเดิม
-- เพราะผู้ใช้ทั่วไปต้องบันทึกประวัติได้ตอนสร้างเอกสารและตอนพิมพ์
-- และยังไม่มี policy แก้ไขหรือลบเหมือนเดิม เพราะสมุดบันทึกหลักฐาน
-- ที่แก้ย้อนหลังได้จะใช้เป็นหลักฐานไม่ได้
-- =====================================================================

drop policy if exists audit_logs_select on public.audit_logs;
create policy audit_logs_select on public.audit_logs
  for select to authenticated
  using (
    org_id = public.get_my_org_id()
    and public.get_my_role() = 'admin'
  );


-- =====================================================================
-- คำสั่งตรวจสอบ (รันแล้วดูผลได้เลย)
-- =====================================================================

-- ตรวจข้อ 1: policy ของ audit_logs ต้องมี 2 ข้อเท่านั้น คือ SELECT และ INSERT
-- ผลที่ถูกต้อง: ได้ 2 แถว ไม่มี UPDATE และไม่มี DELETE
select
  policyname as "ชื่อกฎ",
  cmd        as "คำสั่ง"
from pg_policies
where schemaname = 'public'
  and tablename = 'audit_logs'
order by cmd;

-- ตรวจข้อ 2: กฎการอ่านต้องมีเงื่อนไขบทบาทผู้ดูแลระบบอยู่ในนั้นแล้ว
-- ผลที่ถูกต้อง: ได้ 1 แถว และช่อง "ผลตรวจ" ขึ้น OK
select
  policyname as "ชื่อกฎ",
  qual       as "เงื่อนไขตอนอ่าน",
  case
    when qual like '%get_my_role%' then 'OK'
    else 'ผิด — ยังไม่ได้จำกัดเฉพาะผู้ดูแลระบบ'
  end        as "ผลตรวจ"
from pg_policies
where schemaname = 'public'
  and tablename = 'audit_logs'
  and cmd = 'SELECT';
