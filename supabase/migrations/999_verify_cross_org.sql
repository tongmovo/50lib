-- =====================================================================
-- 999_verify_cross_org.sql
-- ทดสอบว่ากฎความปลอดภัยกันข้อมูลข้ามองค์กรได้จริง
--
-- ไฟล์นี้ **ไม่ใช่ migration** ไม่ได้สร้างหรือแก้โครงสร้างอะไรถาวร
-- เป็นชุดคำสั่งทดสอบที่สร้างข้อมูลจำลองขึ้นมาชั่วคราว ตรวจผล แล้วยกเลิกทิ้งทั้งหมดเมื่อจบ
--
-- -------------------------------------------------------------------
-- ทำไมต้องทดสอบแบบนี้
-- -------------------------------------------------------------------
-- ระบบจริงมีองค์กรเดียว จึงไม่มีข้อมูลขององค์กรอื่นให้ลองแอบดู
-- ถ้าจะทดสอบด้วยการสมัครบัญชีจริงและสร้างบริษัทที่สองขึ้นมา
-- จะมีข้อมูลทดสอบค้างอยู่ในฐานข้อมูลจริงตอนส่งมอบ ซึ่งไม่ควรเกิดขึ้น
--
-- ไฟล์นี้จึงสร้างองค์กรปลอมขึ้นมา 1 แห่งพร้อมข้อมูลข้างใน
-- แล้วสวมบทเป็นผู้ใช้ขององค์กรจริง เพื่อลองอ่านและลองเขียนข้ามไปยังองค์กรปลอมนั้น
-- ผลที่ถูกต้องคือต้องทำไม่ได้ทั้งสองอย่าง
--
-- -------------------------------------------------------------------
-- แก้ไขจากรอบก่อน (21 ส.ค. 2026)
-- -------------------------------------------------------------------
-- รอบก่อนสคริปต์นี้สร้างเอกสารปลอมเป็นสถานะ "ออกแล้ว" ตั้งแต่แรก
-- แล้วค่อยเพิ่มรายการเงินได้ทีหลัง จึงไปชนกฎกันแก้เอกสารที่ออกแล้ว (migration 010)
-- แล้วขึ้น error ว่า "เอกสารนี้ออกไปแล้ว แก้ไขรายการเงินได้ไม่ได้"
--
-- **กฎนั้นทำงานถูกต้องแล้ว ไม่ใช่บั๊ก** เป็นสคริปต์ทดสอบเองที่เรียงลำดับผิด
-- รอบนี้จึงแก้เป็นลำดับเดียวกับที่ระบบจริงใช้ตอนออกเอกสาร คือ
--     สร้างเป็นใบร่างก่อน -> ใส่รายการเงินได้ -> แล้วค่อยเปลี่ยนสถานะเป็นออกแล้ว
-- วิธีนี้ไม่ต้องปิดกฎความปลอดภัยชั่วคราวเลย ซึ่งปลอดภัยกว่า
-- และยังได้ผลพลอยได้คือพิสูจน์ไปในตัวว่าลำดับที่ระบบจริงใช้นั้นถูกต้อง
--
-- -------------------------------------------------------------------
-- วิธีใช้
-- -------------------------------------------------------------------
-- 1. คัดลอกทั้งไฟล์นี้ไปวางใน Supabase SQL Editor แล้วกด Run
-- 2. ดูผลตามที่อธิบายไว้ในแต่ละข้อ
-- 3. ทุกอย่างที่สร้างขึ้นจะถูกยกเลิกทิ้งอัตโนมัติเมื่อจบ (rollback)
--
-- **ปลอดภัยกับข้อมูลจริง** ไม่มีอะไรถูกบันทึกลงฐานข้อมูลถาวร
-- =====================================================================

-- =====================================================================
-- คำสั่งวินิจฉัยด่วน (ไม่บังคับ รันแยกได้ ไม่แก้ข้อมูลอะไร)
--
-- ใช้ตอนสงสัยว่าผลการทดสอบผิดปกติ เพื่อดูว่าตอนนี้กำลังทำงานด้วยสิทธิ์อะไร
-- คัดลอกเฉพาะ 5 บรรทัดข้างล่างนี้ (ลบเครื่องหมาย -- ออกก่อน) ไปรันใน New query
--
-- ผลที่ได้จะบอกว่า
--   สิทธิ์ที่ใช้อยู่ = postgres  และ  องค์กรของฉัน = ว่าง
--     -> แปลว่ากำลังทำงานด้วยสิทธิ์เจ้าของฐานข้อมูล ซึ่งข้ามกฎ RLS ได้ทั้งหมด
--        เป็นเรื่องปกติเมื่อรันคำสั่งเดี่ยว ๆ ใน SQL Editor **ไม่ใช่ช่องโหว่**
--        และแปลว่าห้ามใช้ผลจากการรันแบบนี้มาตัดสินเรื่องความปลอดภัย
--
-- select
--   current_user                                        as "สิทธิ์ที่ใช้อยู่",
--   public.get_my_org_id()                              as "องค์กรของฉัน",
--   (select count(*) from public.organizations)         as "เห็นองค์กรกี่แถว",
--   (select count(*) from public.payees)                as "เห็นผู้รับเงินกี่แถว";
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- ขั้นที่ 1 — สร้างองค์กรปลอมพร้อมข้อมูลข้างใน (ชั่วคราว)
--
-- ลำดับสำคัญมาก ต้องเป็น ใบร่าง -> ใส่รายการ -> เปลี่ยนเป็นออกแล้ว
-- เพราะกฎในไฟล์ 010 ห้ามแตะรายการเงินได้ของเอกสารที่ออกไปแล้ว
-- ---------------------------------------------------------------------
do $$
declare
  v_fake_org   uuid;
  v_fake_payee uuid;
  v_fake_cert  uuid;
begin
  insert into public.organizations (name, tax_id, branch)
  values ('[ทดสอบ] บริษัทองค์กรอื่น จำกัด', '9999999999999', '00000')
  returning id into v_fake_org;

  insert into public.payees (org_id, entity_type, tax_id, name, branch)
  values (v_fake_org, 'juristic', '8888888888888', '[ทดสอบ] ผู้รับเงินขององค์กรอื่น', '00000')
  returning id into v_fake_payee;

  /* ขั้นที่ 1.1 สร้างเป็น "ใบร่าง" ก่อน ยังไม่ใส่เลขที่เอกสาร */
  insert into public.wht_certificates (
    org_id, form_type, payee_id, issue_date,
    total_amount, total_tax, status
  )
  values (
    v_fake_org, 'pnd3', v_fake_payee, current_date,
    123456.78, 3703.70, 'draft'
  )
  returning id into v_fake_cert;

  /* ขั้นที่ 1.2 ใส่รายการเงินได้ตอนที่ยังเป็นใบร่าง จึงผ่านกฎในไฟล์ 010 */
  insert into public.wht_certificate_items (certificate_id, income_type_code, amount, rate, tax_amount)
  values (v_fake_cert, 'service', 123456.78, 3, 3703.70);

  /* ขั้นที่ 1.3 ค่อยเปลี่ยนเป็น "ออกแล้ว" พร้อมใส่เลขที่ เหมือนที่ระบบจริงทำ */
  update public.wht_certificates
  set doc_no = 'TEST-9999-0001',
      status = 'issued'
  where id = v_fake_cert;

  insert into public.doc_counters (org_id, period, last_seq)
  values (v_fake_org, '9999', 1);

  insert into public.audit_logs (org_id, action, entity, entity_id)
  values (v_fake_org, 'create', 'wht_certificates', v_fake_cert);

  /*
    จำรหัสขององค์กรปลอมและเอกสารปลอมไว้ในตัวแปรของรายการนี้
    เพื่อให้ขั้นตอนทดสอบข้างล่างอ้างถึงได้อย่างแม่นยำ
    แม้ตอนนั้นจะสวมบทเป็นผู้ใช้ที่มองไม่เห็นข้อมูลพวกนี้แล้วก็ตาม
  */
  perform set_config('app.fake_org', v_fake_org::text, true);
  perform set_config('app.fake_cert', v_fake_cert::text, true);

  raise notice 'สร้างข้อมูลทดสอบขององค์กรปลอมเรียบร้อย (รหัสองค์กรปลอม %)', v_fake_org;
end $$;


-- ---------------------------------------------------------------------
-- ขั้นที่ 2 — สวมบทเป็นผู้ใช้ขององค์กรจริง
--
-- คำสั่ง set local role authenticated คือการบอกฐานข้อมูลว่า
-- "ต่อจากนี้ให้ถือว่าคำสั่งมาจากผู้ใช้ที่ล็อกอินผ่านเว็บ ไม่ใช่ผู้ดูแลฐานข้อมูล"
-- ซึ่งทำให้กฎ RLS เริ่มทำงาน
--
-- ส่วน request.jwt.claims คือการบอกว่าเป็นผู้ใช้คนไหน
-- ใช้รหัสของผู้ใช้จริงที่มีอยู่ เพื่อให้ฟังก์ชัน get_my_org_id() หาสังกัดเจอ
-- ---------------------------------------------------------------------
do $$
declare
  v_user_id uuid;
  v_org_id  uuid;
begin
  select p.id, p.org_id into v_user_id, v_org_id
  from public.profiles p
  where p.is_active = true
    and p.org_id is not null
    and p.org_id::text is distinct from current_setting('app.fake_org', true)
  order by p.created_at
  limit 1;

  if v_user_id is null then
    raise exception 'ไม่พบผู้ใช้ขององค์กรจริงในระบบ จึงทดสอบต่อไม่ได้';
  end if;

  perform set_config(
    'request.jwt.claims',
    json_build_object('sub', v_user_id, 'role', 'authenticated')::text,
    true
  );

  raise notice 'สวมบทเป็นผู้ใช้รหัส % สังกัดองค์กรจริง %', v_user_id, v_org_id;
end $$;

set local role authenticated;


-- ---------------------------------------------------------------------
-- ขั้นที่ 2.5 — ด่านตรวจว่าการสวมบทได้ผลจริง (สำคัญมาก ห้ามข้าม)
--
-- ทำไมต้องมีด่านนี้
-- ถ้าการสวมบทไม่ได้ผล คำสั่งจะยังทำงานด้วยสิทธิ์เจ้าของฐานข้อมูล
-- ซึ่งข้ามกฎ RLS ได้ทั้งหมด และฟังก์ชัน get_my_org_id() จะคืนค่าว่าง
-- ผลคือขั้นที่ 4 จะนับ "ทุกแถวในตาราง" แล้วรายงานออกมาเหมือนเจอช่องโหว่
-- ทั้งที่ความจริงคือแค่การทดสอบไม่ได้เริ่มทำงาน
--
-- ด่านนี้จึงหยุดทั้งสคริปต์ทันทีพร้อมบอกสาเหตุ ดีกว่าปล่อยให้อ่านผลผิด
-- ---------------------------------------------------------------------
do $$
declare
  v_role text := current_user;
  v_org  uuid := public.get_my_org_id();
begin
  if v_role <> 'authenticated' then
    raise exception
      'การสวมบทไม่ได้ผล ตอนนี้ยังทำงานด้วยสิทธิ์ % อยู่ ซึ่งข้ามกฎความปลอดภัยได้ทั้งหมด จึงทดสอบต่อไม่ได้ กรุณารันไฟล์นี้ทั้งไฟล์ในครั้งเดียว อย่ารันแยกทีละส่วน',
      v_role;
  end if;

  if v_org is null then
    raise exception
      'สวมบทเป็นผู้ใช้แล้ว แต่ระบบหาสังกัดองค์กรไม่เจอ (get_my_org_id คืนค่าว่าง) จึงทดสอบต่อไม่ได้ เพราะผลลัพธ์จะอ่านผิดทั้งหมด';
  end if;

  raise notice 'ด่านตรวจผ่าน: ทำงานด้วยสิทธิ์ % สังกัดองค์กร %', v_role, v_org;
end $$;


-- ---------------------------------------------------------------------
-- ขั้นที่ 3 — ลองอ่านข้อมูลขององค์กรปลอมจากทุกตาราง
--
-- ผลที่ถูกต้อง: ทุกแถวต้องขึ้น "ผ่าน" และช่องจำนวนต้องเป็น 0 ทั้งหมด
-- ถ้าแถวไหนขึ้น "ไม่ผ่าน" แปลว่าตารางนั้นมองเห็นข้อมูลขององค์กรอื่นได้ ต้องรีบแก้
--
-- ใช้การอ้างด้วยรหัสที่จำไว้ตั้งแต่ขั้นที่ 1 แทนการอ้างด้วยค่าที่พิมพ์เอง
-- จะได้ไม่เผลอไปนับข้อมูลจริงของลูกค้าว่าเป็นข้อมูลทดสอบ
-- ---------------------------------------------------------------------
select
  'organizations'                                                          as "ตาราง",
  count(*)                                                                 as "เห็นข้อมูลองค์กรอื่นกี่แถว",
  case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end                    as "ผลตรวจ"
from public.organizations
where id::text = current_setting('app.fake_org', true)

union all
select 'payees', count(*), case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end
from public.payees
where org_id::text = current_setting('app.fake_org', true)

union all
select 'wht_certificates', count(*), case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end
from public.wht_certificates
where org_id::text = current_setting('app.fake_org', true)

union all
select 'wht_certificate_items', count(*), case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end
from public.wht_certificate_items
where certificate_id::text = current_setting('app.fake_cert', true)

union all
select 'doc_counters', count(*), case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end
from public.doc_counters
where org_id::text = current_setting('app.fake_org', true)

union all
select 'audit_logs', count(*), case when count(*) = 0 then 'ผ่าน' else 'ไม่ผ่าน' end
from public.audit_logs
where org_id::text = current_setting('app.fake_org', true);


-- ---------------------------------------------------------------------
-- ขั้นที่ 4 — ตรวจซ้ำแบบกวาดทั้งตาราง ว่าไม่มีแถวไหนเลยที่ไม่ใช่ขององค์กรตัวเอง
--
-- ต่างจากขั้นที่ 3 ตรงที่ไม่ได้เจาะจงแค่ข้อมูลทดสอบ แต่ตรวจทุกแถวที่มองเห็น
--
-- ***** อ่านก่อนตีความผล *****
-- คำสั่งนี้ **ต้องรันพร้อมกับทั้งไฟล์เท่านั้น** ห้ามคัดลอกไปรันเดี่ยว ๆ
-- ถ้ารันเดี่ยว จะทำงานด้วยสิทธิ์เจ้าของฐานข้อมูลซึ่งข้ามกฎ RLS ได้
-- และ get_my_org_id() จะคืนค่าว่าง ทำให้เงื่อนไข "ไม่ใช่องค์กรตัวเอง" เป็นจริงกับ **ทุกแถว**
-- ผลที่ได้จะดูเหมือนเจอช่องโหว่ ทั้งที่จริงแค่การทดสอบไม่ได้เริ่มทำงาน
-- (ด่านตรวจในขั้นที่ 2.5 กันกรณีนี้ไว้แล้ว ถ้ารันทั้งไฟล์จะไม่มีทางเกิด)
--
-- ผลที่ถูกต้อง: ต้องไม่มีแถวใดถูกส่งกลับมาเลย (0 rows)
--
-- คอลัมน์ "สิทธิ์ที่ใช้อยู่" กับ "องค์กรของฉัน" ใส่ไว้ให้ตรวจบริบทได้ทันที
-- ถ้าเห็นแถวใด ๆ แล้วสองคอลัมน์นี้ไม่ใช่ authenticated และไม่ใช่รหัสองค์กรจริง
-- แปลว่าอ่านผลไม่ได้ ต้องรันใหม่ทั้งไฟล์ ไม่ใช่ช่องโหว่
-- ---------------------------------------------------------------------
select
  'organizations'                as "ตาราง",
  count(*)                       as "แถวที่ไม่ใช่ขององค์กรตัวเอง",
  current_user                   as "สิทธิ์ที่ใช้อยู่",
  public.get_my_org_id()         as "องค์กรของฉัน"
from public.organizations where id is distinct from public.get_my_org_id()
having count(*) > 0

union all
select 'payees', count(*), current_user, public.get_my_org_id()
from public.payees where org_id is distinct from public.get_my_org_id()
having count(*) > 0

union all
select 'wht_certificates', count(*), current_user, public.get_my_org_id()
from public.wht_certificates where org_id is distinct from public.get_my_org_id()
having count(*) > 0

union all
select 'doc_counters', count(*), current_user, public.get_my_org_id()
from public.doc_counters where org_id is distinct from public.get_my_org_id()
having count(*) > 0

union all
select 'audit_logs', count(*), current_user, public.get_my_org_id()
from public.audit_logs where org_id is distinct from public.get_my_org_id()
having count(*) > 0;


-- ---------------------------------------------------------------------
-- ขั้นที่ 5 — ลองเขียนข้อมูลเข้าองค์กรอื่น ต้องถูกปฏิเสธ
--
-- อ่านผลได้ที่แท็บ Messages ด้านล่างของ SQL Editor
-- ผลที่ถูกต้อง: ขึ้นข้อความ "ผ่าน (ถูกปฏิเสธตามที่ควร)" ทั้ง 2 ข้อ
-- ---------------------------------------------------------------------
do $$
declare
  v_fake_org uuid := current_setting('app.fake_org', true)::uuid;
  v_blocked  boolean;
begin
  /* ข้อ 5.1 ลองเพิ่มรายชื่อผู้รับเงินเข้าองค์กรอื่น */
  v_blocked := false;
  begin
    insert into public.payees (org_id, entity_type, tax_id, name)
    values (v_fake_org, 'juristic', '7777777777777', '[ทดสอบ] แอบเขียนข้ามองค์กร');
  exception when others then
    v_blocked := true;
  end;

  if v_blocked then
    raise notice 'ผลตรวจข้อ 5.1 (เพิ่มรายชื่อข้ามองค์กร): ผ่าน (ถูกปฏิเสธตามที่ควร)';
  else
    raise warning 'ผลตรวจข้อ 5.1: ไม่ผ่าน — เขียนข้อมูลเข้าองค์กรอื่นได้ ต้องรีบแก้';
  end if;

  /* ข้อ 5.2 ลองแก้ชื่อบริษัทขององค์กรอื่น */
  v_blocked := false;
  begin
    update public.organizations
    set name = '[ทดสอบ] แอบแก้ชื่อองค์กรอื่น'
    where id = v_fake_org;

    /*
