-- -------------------------------------------------------------------
-- ปัญหาที่ไฟล์นี้แก้
-- -------------------------------------------------------------------
-- Supabase เก็บบัญชีผู้ใช้ไว้ที่ตาราง auth.users (คนละที่กับตารางของเรา)
-- ตารางนั้นมีแค่อีเมลกับรหัสผ่าน ไม่รู้จักว่าใครสังกัดบริษัทไหน มีสิทธิ์ระดับใด
-- ข้อมูลส่วนนั้นอยู่ในตาราง public.profiles ของเรา
--
-- ถ้าไม่มี trigger นี้ ทุกครั้งที่แอดมินเพิ่มผู้ใช้ใหม่ใน Dashboard
-- จะต้องมานั่งเพิ่มแถวใน profiles เองด้วยมือทุกครั้ง ลืมเมื่อไหร่ผู้ใช้คนนั้นล็อกอินได้
-- แต่มองไม่เห็นข้อมูลอะไรเลย ไฟล์นี้จึงทำให้เกิดขึ้นเองอัตโนมัติ
-- =====================================================================


-- ---------------------------------------------------------------------
-- ส่วนที่ 1 — ยอมให้ profiles.org_id ว่างได้ชั่วคราว
--
-- เดิมในไฟล์ 001 กำหนดว่า org_id ห้ามว่าง (not null)
-- แต่ถ้ายังไม่มีบริษัทสักแถวในระบบ trigger จะหาบริษัทไม่เจอ
-- แล้วการเพิ่มผู้ใช้ใหม่จะพังทั้งกระบวนการ (สร้างบัญชีไม่ได้เลย)
--
-- จึงผ่อนกฎข้อนี้ลง เพื่อให้ระบบไม่พังในกรณีที่ตั้งค่ายังไม่ครบ
-- การผ่อนกฎเป็นการแก้แบบปลอดภัย ไม่กระทบข้อมูลเดิมที่มีอยู่แล้ว
--
-- !!! คำเตือนสำคัญ !!!
-- ต้องมีข้อมูลบริษัทในตาราง organizations อย่างน้อย 1 แถว "ก่อน" เพิ่มผู้ใช้เสมอ
-- เพราะผู้ใช้ที่ org_id ว่าง จะล็อกอินได้ก็จริง แต่จะมองไม่เห็นข้อมูลใด ๆ เลย
-- (กฎ RLS ในไฟล์ 004 เทียบ org_id ของผู้ใช้กับข้อมูลแต่ละแถว ถ้าฝั่งผู้ใช้ว่างก็เทียบไม่ติด)
-- ดูวิธีแก้ที่ท้ายไฟล์นี้ หัวข้อ "คำสั่งช่วยตั้งค่าครั้งแรก"
-- ---------------------------------------------------------------------
alter table public.profiles alter column org_id drop not null;


-- ---------------------------------------------------------------------
-- ส่วนที่ 2 — ฟังก์ชันที่จะถูกเรียกทุกครั้งที่มีผู้ใช้ใหม่
--
-- ใช้ SECURITY DEFINER เพราะฟังก์ชันนี้ต้องเขียนลงตาราง profiles
-- ซึ่งตามกฎ RLS ในไฟล์ 004 อนุญาตให้เฉพาะ admin เขียนได้
-- ตัวผู้ใช้ใหม่ที่เพิ่งถูกสร้างย่อมไม่มีสิทธิ์นั้น จึงต้องให้ฟังก์ชันทำงานด้วยสิทธิ์เจ้าของแทน
-- ---------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_org_id uuid;
  v_full_name text;
begin
  -- ระบบนี้ใช้กับบริษัทเดียว (ยืนยันกับลูกค้าแล้ว)
  -- จึงหยิบบริษัทแถวแรกที่สร้างไว้มาใช้เป็นสังกัดของผู้ใช้ใหม่ทุกคน
  -- ถ้ายังไม่มีบริษัทเลย ค่าที่ได้จะเป็นค่าว่าง ซึ่งยอมรับได้ (ดูคำเตือนส่วนที่ 1)
  select o.id
    into v_org_id
  from public.organizations o
  order by o.created_at asc
  limit 1;

  -- ใช้ชื่อจากส่วนหน้าเครื่องหมาย @ ของอีเมลไปพลางก่อน
  -- เช่น somchai@email.com จะได้ชื่อเริ่มต้นว่า somchai
  -- ผู้ใช้แก้ชื่อจริงเองได้ทีหลังในหน้าตั้งค่า
  v_full_name := nullif(split_part(coalesce(new.email, ''), '@', 1), '');

  insert into public.profiles (id, org_id, full_name, role, is_active)
  values (
    new.id,
    v_org_id,
    v_full_name,
    'user',   -- ทุกคนเริ่มต้นเป็นผู้ใช้ธรรมดาเสมอ
    true
  )
  on conflict (id) do nothing;   -- ถ้ามีแถวอยู่แล้วก็ปล่อยผ่าน ไม่ทับของเดิม

  return new;

exception
  -- ถ้าเกิดข้อผิดพลาดอะไรก็ตามในการสร้าง profile
  -- ให้บันทึกคำเตือนไว้ใน log แต่ต้องไม่ทำให้การสร้างบัญชีผู้ใช้ล้มเหลวตามไปด้วย
  -- (บัญชีที่สร้างสำเร็จแต่ยังไม่มี profile แก้ตามทีหลังได้ ง่ายกว่าสร้างบัญชีไม่ได้เลย)
  when others then
    raise warning '[50bis] สร้างแถวใน profiles อัตโนมัติไม่สำเร็จ สำหรับผู้ใช้ % : %', new.id, sqlerrm;
    return new;
end;
$$;

comment on function public.handle_new_user() is
  'สร้างแถวใน public.profiles อัตโนมัติเมื่อมีผู้ใช้ใหม่ใน auth.users';


-- ---------------------------------------------------------------------
-- ส่วนที่ 3 — ผูกฟังก์ชันเข้ากับตาราง auth.users
--
-- ทำงานหลังจากผู้ใช้ถูกสร้างสำเร็จแล้ว (after insert)
-- ครอบคลุมทุกช่องทางที่สร้างผู้ใช้ ทั้งการกดเพิ่มใน Dashboard และการเรียกผ่าน Admin API
-- ใช้ drop ก่อน create เพื่อให้รันไฟล์นี้ซ้ำได้โดยไม่ error
-- ---------------------------------------------------------------------
drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


