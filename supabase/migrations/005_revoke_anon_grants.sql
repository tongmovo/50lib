-- =====================================================================
-- 005_revoke_anon_grants.sql
-- ปิดสิทธิ์ระดับตารางของ role `anon` (ผู้ที่ยังไม่ได้ล็อกอิน) ให้หมด
-- ต้องรันหลัง 004
--
-- -------------------------------------------------------------------
-- ที่มาของปัญหา
-- -------------------------------------------------------------------
-- ตอนรันไฟล์ 999 ข้อ 7 เพื่อตรวจสอบ พบว่า role `anon` มีสิทธิ์ระดับตาราง
-- ครบทุกคำสั่ง (SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER)
-- บนตารางทุกตารางใน schema public
--
-- นี่ไม่ใช่ความผิดพลาดของไฟล์ 001-004 แต่เป็น "ค่าตั้งต้นของ Supabase" เอง
-- Supabase ตั้ง default privileges ไว้ว่า ตารางใหม่ทุกตารางที่สร้างใน schema public
-- จะแจกสิทธิ์ให้ anon โดยอัตโนมัติ (เพราะออกแบบมาเผื่อเว็บที่มีหน้าสาธารณะ)
--
-- -------------------------------------------------------------------
-- ทำไมต้องปิด ทั้งที่เปิด RLS ไว้แล้ว
-- -------------------------------------------------------------------
-- RLS ที่ตั้งไว้ในไฟล์ 004 กันไว้อยู่แล้วชั้นหนึ่ง (ทุก policy ระบุ `to authenticated`
-- ดังนั้น anon จึงไม่มี policy ไหนรองรับ = อ่านหรือเขียนอะไรไม่ได้อยู่ดี)
--
-- แต่ระบบนี้เก็บข้อมูลภาษีและข้อมูลส่วนบุคคลของผู้รับเงิน จึงควรกัน 2 ชั้น
-- (defense in depth = ถ้าชั้นแรกพลาด ยังมีชั้นที่สองรับไว้)
-- เช่น ถ้าวันหนึ่งมีคนเผลอสร้างตารางใหม่แล้วลืมเปิด RLS
-- หรือเผลอเขียน policy ผิดพลาด ชั้นสิทธิ์ระดับตารางนี้จะยังกันไว้ให้
--
-- ระบบ 50bis ไม่มีหน้าไหนเลยที่คนยังไม่ล็อกอินต้องเข้าถึงข้อมูลในตารางเหล่านี้
-- ทุกหน้าใช้งานต้องล็อกอินก่อนทั้งหมด
-- ส่วนตัวการล็อกอินเองใช้ Supabase Auth ซึ่งอยู่คนละ schema (`auth`)
-- และเป็นคนละกลไกกับสิทธิ์ตารางใน schema `public` ที่กำลังปิดอยู่นี้
-- การรันไฟล์นี้จึง **ไม่กระทบการล็อกอิน / สมัครสมาชิก / รีเซ็ตรหัสผ่าน** แต่อย่างใด
--
-- -------------------------------------------------------------------
-- หมายเหตุ: คำสั่ง REVOKE รันซ้ำได้ปลอดภัย
-- ถ้าสิทธิ์ถูกถอนไปแล้ว การสั่งถอนซ้ำจะไม่เกิด error ใด ๆ
-- =====================================================================


-- ---------------------------------------------------------------------
-- ส่วนที่ 1 — ถอนสิทธิ์ที่ anon มีอยู่แล้วในปัจจุบัน
-- ---------------------------------------------------------------------

-- ตารางทั้งหมด (รวมทั้ง 8 ตารางของระบบนี้)
revoke all on all tables in schema public from anon;

-- ตัวนับลำดับอัตโนมัติ (sequences) — ตอนนี้ระบบยังไม่มี แต่ปิดกันไว้ล่วงหน้า
revoke all on all sequences in schema public from anon;

-- ฟังก์ชันทั้งหมดใน schema public
-- รวมถึง get_my_org_id() และ get_my_role() ที่สร้างไว้ในไฟล์ 004
-- (ในไฟล์ 004 ถอนสิทธิ์ 2 ตัวนี้จาก anon ไว้แล้ว บรรทัดนี้คือกวาดให้ครบทุกตัว)
revoke all on all functions in schema public from anon;


-- ---------------------------------------------------------------------
-- ส่วนที่ 2 — กันปัญหาเดิมไม่ให้เกิดซ้ำในอนาคต
--
-- ส่วนที่ 1 ข้างบนถอนสิทธิ์ของตารางที่ "มีอยู่ ณ ตอนนี้" เท่านั้น
-- ถ้าวันหลังสร้างตารางใหม่เพิ่ม ตารางใหม่นั้นจะได้สิทธิ์ให้ anon อีกรอบ
-- คำสั่งข้างล่างนี้คือการแก้ที่ต้นเหตุ — สั่งล่วงหน้าว่า
-- "ตารางใหม่ที่จะสร้างต่อจากนี้ ห้ามแจกสิทธิ์ให้ anon"
--
-- หมายเหตุสำคัญ: คำสั่ง alter default privileges มีผลกับ "ผู้สร้างตาราง" คนที่รันคำสั่งนี้
-- ซึ่งก็คือ role `postgres` ที่ใช้ตอนรันใน SQL Editor และเป็นเจ้าของตารางทั้ง 8 ตารางอยู่แล้ว
-- ถ้าในอนาคตมีการสร้างตารางด้วย role อื่น ให้กลับมารันคำสั่งกลุ่มนี้ซ้ำด้วย role นั้น
-- ---------------------------------------------------------------------

alter default privileges in schema public revoke all on tables from anon;

-- ปิดให้ครบทั้ง 3 ประเภทด้วยเหตุผลเดียวกัน จะได้ไม่ต้องกลับมาแก้อีก
alter default privileges in schema public revoke all on sequences from anon;
alter default privileges in schema public revoke all on functions from anon;


